
'use server';

import { ai } from '@/ai/genkit';
import { generateAzureOpenAIJson, isAzureOpenAIConfigured } from '@/lib/azure-openai';
import { z } from 'genkit';

const FullInterviewAnalysisInputSchema = z.object({
  role: z.string(),
  transcript: z.array(z.object({
    role: z.enum(['user', 'ai']),
    content: z.string(),
    sectionId: z.enum(['communication', 'technical', 'resume_projects']).optional(),
    sectionTitle: z.string().optional(),
  }))
});

const FullInterviewAnalysisOutputSchema = z.object({
  overallScore: z.number(),
  summary: z.string().describe('A high-level executive summary of the performance.'),
  strengths: z.array(z.string()).describe('Top 3-5 strengths demonstrated.'),
  weaknesses: z.array(z.string()).describe('Areas for improvement.'),
  htmlReport: z.string().describe('Leave this as an empty string. HTML will be generated by the application layer.'),
  sectionFeedback: z.array(z.object({
    sectionId: z.enum(['communication', 'technical', 'resume_projects']),
    sectionTitle: z.string(),
    score: z.number().describe('0-100 score for this interview section.'),
    summary: z.string().describe('A reviewer-friendly summary of performance in this section.'),
    strengths: z.array(z.string()).describe('Section-specific strengths.'),
    improvements: z.array(z.string()).describe('Section-specific improvement areas.'),
  })).describe('A section-by-section evaluation for communication, technical depth, and resume-project discussion.'),
  rubric: z.object({
    competencies: z.array(z.object({
      name: z.enum([
        'Problem Solving',
        'Technical Depth',
        'Communication',
        'Clarity & Structure',
        'Practicality',
        'Collaboration',
        'Ownership',
        'Behavioral Signals',
      ]),
      score: z.number().describe('0-100 for this competency.'),
      evidence: z.array(z.object({
        quote: z.string().describe('A short quote or paraphrase from the transcript (max ~1-2 sentences).'),
        speaker: z.enum(['user', 'ai']).describe('Who said the quoted line.'),
        whyItMatters: z.string().describe('Why this quote supports the competency score.'),
      })).describe('2-4 evidence items per competency.'),
    })).describe('Competency-based rubric scoring with evidence.'),
    overallNotes: z.string().describe('Short rubric notes for reviewers (1-2 paragraphs).'),
  }),
  technicalFeedback: z.string().describe('Detailed assessment of technical knowledge.'),
  behavioralFeedback: z.string().describe('Assessment of soft skills and communication.'),
  questionFeedback: z.array(z.object({
    question: z.string(),
    sectionTitle: z.string().describe('The interview section this question belongs to.'),
    feedback: z.string(),
    score: z.number(),
    evidence: z.array(z.object({
      quote: z.string().describe('A short quote or paraphrase from the transcript supporting this score.'),
      speaker: z.enum(['user', 'ai']),
    })).describe('1-2 evidence snippets for this question.'),
  })).describe('Specific feedback for each individual question asked.'),
  hiringRecommendation: z.enum(['Strong Hire', 'Hire', 'Leaning Hire', 'No Hire']).describe('Final hiring recommendation.')
});

export type FullInterviewAnalysisInput = z.infer<typeof FullInterviewAnalysisInputSchema>;
export type FullInterviewAnalysisOutput = z.infer<typeof FullInterviewAnalysisOutputSchema>;

const analysisPrompt = ai.definePrompt({
  name: 'fullInterviewAnalysisPrompt',
  input: { schema: FullInterviewAnalysisInputSchema },
  output: { schema: FullInterviewAnalysisOutputSchema },
  prompt: `You are a Senior Principal Interviewer conducting a post-interview debrief for the role of {{{role}}}.
  
  You have just finished an interview. Below is the full transcript of the conversation.
  
  TRANSCRIPT:
  {{#each transcript}}
  - {{role}} {{#if sectionTitle}}[{{sectionTitle}}]{{/if}}: {{content}}
  {{/each}}
  
  YOUR TASK:
  Perform a deep-dive analysis of the candidate's performance.
  1. Evaluate the candidate across only the sections present in the transcript:
     - Communication and Attitude
     - Technical Questions
     - Resume Projects, only when resume-project questions were actually asked
  2. Evaluate technical depth based on their answers.
  3. Assess communication clarity, professionalism, and attitude.
  4. Identify specific patterns in their strengths and gaps.
  5. Provide specific feedback and a score (0-100) for EACH question in the transcript.
  6. Provide section-by-section feedback with score, summary, strengths, and improvements for sections that appear in the transcript.
  7. Provide a final overall score (0-100) and a clear hiring recommendation.
  8. Provide a competency-based rubric with scores (0-100) and concrete evidence quotes/paraphrases from the transcript.
  9. Set htmlReport to an empty string.

  Format your final report as purely valid JSON matching the output schema.`,
});

function buildTranscriptText(input: FullInterviewAnalysisInput) {
  return input.transcript
    .map((message) => `- ${message.role}${message.sectionTitle ? ` [${message.sectionTitle}]` : ''}: ${message.content}`)
    .join('\n');
}

function buildAzureAnalysisPrompt(input: FullInterviewAnalysisInput) {
  return `Role: ${input.role}

TRANSCRIPT:
${buildTranscriptText(input)}

Return one JSON object with this exact shape:
{
  "overallScore": number,
  "summary": string,
  "strengths": string[],
  "weaknesses": string[],
  "htmlReport": "",
  "sectionFeedback": [
    {
      "sectionId": "communication" | "technical" | "resume_projects",
      "sectionTitle": string,
      "score": number,
      "summary": string,
      "strengths": string[],
      "improvements": string[]
    }
  ],
  "rubric": {
    "competencies": [
      {
        "name": "Problem Solving" | "Technical Depth" | "Communication" | "Clarity & Structure" | "Practicality" | "Collaboration" | "Ownership" | "Behavioral Signals",
        "score": number,
        "evidence": [
          { "quote": string, "speaker": "user" | "ai", "whyItMatters": string }
        ]
      }
    ],
    "overallNotes": string
  },
  "technicalFeedback": string,
  "behavioralFeedback": string,
  "questionFeedback": [
    {
      "question": string,
      "sectionTitle": string,
      "feedback": string,
      "score": number,
      "evidence": [
        { "quote": string, "speaker": "user" | "ai" }
      ]
    }
  ],
  "hiringRecommendation": "Strong Hire" | "Hire" | "Leaning Hire" | "No Hire"
}

Rules:
- Return JSON only.
- Set htmlReport to an empty string.
- Score every question asked by the interviewer.
- Include only section IDs that appear in the transcript. Do not invent Resume Projects feedback when no resume-project questions were asked.
- Use concrete transcript evidence where possible.`;
}

async function analyzeWithGemini(input: FullInterviewAnalysisInput) {
  const { output } = await analysisPrompt(input);
  if (!output) throw new Error("Gemini failed to generate a final analysis.");
  return output;
}

async function analyzeWithAzureOpenAI(input: FullInterviewAnalysisInput) {
  const output = await generateAzureOpenAIJson<FullInterviewAnalysisOutput>({
    system: "You are a Senior Principal Interviewer. You produce strict JSON only for structured interview evaluations.",
    user: buildAzureAnalysisPrompt(input),
    temperature: 0.2,
  });

  return FullInterviewAnalysisOutputSchema.parse(output);
}

export async function analyzeFullInterview(input: FullInterviewAnalysisInput): Promise<FullInterviewAnalysisOutput> {
  const preferAzure = process.env.AI_PRIMARY_PROVIDER?.toLowerCase() === 'azure';
  const providers = preferAzure
    ? [analyzeWithAzureOpenAI, analyzeWithGemini]
    : [analyzeWithGemini, analyzeWithAzureOpenAI];

  let lastError: unknown;

  for (const provider of providers) {
    if (provider === analyzeWithAzureOpenAI && !isAzureOpenAIConfigured()) {
      continue;
    }

    try {
      return await provider(input);
    } catch (error) {
      lastError = error;
      console.error("Interview analysis provider failed:", error);
    }
  }

  throw lastError instanceof Error ? lastError : new Error("AI failed to generate a final analysis.");
}
